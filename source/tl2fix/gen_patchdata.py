"""Generates patchdata.h: byte differences only (no game code), plus SHA-256 hashes of each known state."""
import hashlib, sys
def runs(a, b):
    n = min(len(a), len(b)); out = []; i = 0
    while i < n:
        if a[i] != b[i]:
            j = i
            while j < n and any(j + k < n and a[j + k] != b[j + k] for k in range(4)): j += 1
            out.append((i, a[i:j], b[i:j])); i = j
        else: i += 1
    return out
def carr(name, data): return f"static const unsigned char {name}[{len(data)}] = {{" + ",".join(str(x) for x in data) + "};\n"
def sha(b): return hashlib.sha256(b).hexdigest()
o = open('orig/Torchlight2_original.exe','rb').read(); f = open('orig/Torchlight2_fixed.exe','rb').read()
p = open('orig/Torchlight2_patched.exe','rb').read()
mo = open('/home/claude/ogresteam/steam_OgreMain.dll','rb').read(); mf = open('/home/claude/ogresteam/OgreMain.dll','rb').read()
assert len(f) > len(o) and len(p) == len(f) and len(mo) == len(mf)
out = ["/* generated by gen_patchdata.py - byte differences only */\n", "struct run { unsigned off, len; const unsigned char *from, *to; };\n"]
def emit(prefix, a, b, tail=None):
    rs = runs(a, b); s = ""
    for k, (off, x, y) in enumerate(rs): s += carr(f"{prefix}_f{k}", x) + carr(f"{prefix}_t{k}", y)
    s += f"static const struct run {prefix}_runs[] = {{" + ",".join(f"{{{off},{len(x)},{prefix}_f{k},{prefix}_t{k}}}" for k, (off, x, y) in enumerate(rs)) + "};\n"
    s += f"#define {prefix.upper()}_NRUNS {len(rs)}\n"
    return s, rs
s, r1 = emit("exe", o, f[:len(o)]); out.append(s)
out.append(carr("exe_tail", f[len(o):]) + f"#define EXE_ORIG_LEN {len(o)}u\n#define EXE_FIXED_LEN {len(f)}u\n")
s, r2 = emit("upg", p, f); out.append(s)
s, r3 = emit("ogre", mo, mf); out.append(s)
for name, b in (("EXE_ORIG", o), ("EXE_FIXED", f), ("EXE_CHATGPT", p), ("OGRE_ORIG", mo), ("OGRE_FIXED", mf)):
    out.append(f'#define SHA_{name} "{sha(b)}"\n')
open('patchdata.h','w').write("".join(out))
print("exe runs", len(r1), "bytes", sum(len(x) for _, x, _ in r1), "tail", len(f) - len(o), "| upgrade runs", len(r2), "| ogre runs", len(r3))
